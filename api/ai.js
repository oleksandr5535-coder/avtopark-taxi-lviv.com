export default async function handler(req, res) {
  res.setHeader('Content-Type', 'application/json; charset=utf-8');

  if (req.method !== 'POST') {
    return res.status(200).send(JSON.stringify({ ok: false, error: 'Тільки POST' }));
  }

  try {
    const key = process.env.ANTHROPIC_API_KEY;
    if (!key) throw new Error('Немає ANTHROPIC_API_KEY у змінних оточення Vercel');

    let body = req.body;
    if (typeof body === 'string') { try { body = JSON.parse(body); } catch (e) { body = {}; } }
    body = body || {};

    const taskName = String(body.task || '');
    const task = TASKS[taskName];
    if (!task) throw new Error('Невідомий тип задачі');

    const payload = body.payload;
    if (!payload || typeof payload !== 'object') throw new Error('Немає даних для розбору');

    const asText = JSON.stringify(payload);
    if (asText.length > MAX_BODY) throw new Error('Забагато даних (' + asText.length + ' символів)');

    const r = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': key,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({
        model: MODEL,
        max_tokens: MAX_TOKENS,
        system: task.system,
        messages: [{ role: 'user', content: task.prompt(payload) }],
      }),
    });

    const txt = await r.text();
    let j;
    try { j = JSON.parse(txt); }
    catch (e) { throw new Error('Не-JSON від API (' + r.status + '): ' + txt.slice(0, 200)); }

    if (j.error) throw new Error(j.error.message || 'Помилка API');
    if (!Array.isArray(j.content)) throw new Error('Порожня відповідь');

    const out = j.content
      .filter(x => x && x.type === 'text')
      .map(x => x.text)
      .join('\n')
      .trim();

    const u = j.usage || {};
    return res.status(200).send(JSON.stringify({
      ok: true,
      text: out,
      model: j.model || MODEL,
      tokens: { in: u.input_tokens || 0, out: u.output_tokens || 0 },
    }));

  } catch (err) {
    return res.status(200).send(JSON.stringify({ ok: false, error: err.message }));
  }
}
